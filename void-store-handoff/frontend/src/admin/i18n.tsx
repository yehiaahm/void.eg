export type AdminLang = 'en' | 'ar'
export type AdminStrings = Dict

const Ctx = createContext<{ lang: AdminLang; t: Dict; setLang: (l: AdminLang) => void } | null>(null)

export function AdminI18n({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<AdminLang>(() => {
    try {
      const v = localStorage.getItem('void.admin.lang')
      if (v === 'en' || v === 'ar') return v
    } catch {
      /* storage unavailable */
    }
    return 'en'
  })
  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
    document.title = `${lang === 'ar' ? ar.admin : en.admin} — VOID`
  }, [lang])
  const setLang = (l: AdminLang) => {
    setLangState(l)
    try {
      localStorage.setItem('void.admin.lang', l)
    } catch {
      /* storage unavailable */
    }
  }
  return <Ctx.Provider value={{ lang, t: lang === 'ar' ? ar : en, setLang }}>{children}</Ctx.Provider>
}

export function useT() {
  const v = useContext(Ctx)
  if (!v) throw new Error('useT outside AdminI18n')
  return v
}
